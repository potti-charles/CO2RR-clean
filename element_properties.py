def get_property(symbol: str, prop_index: int) -> float:
    """Get a single property value for an element symbol."""
    if symbol not in ELEMENT_DATA:
        return 0.0
    return float(ELEMENT_DATA[symbol][prop_index])


def get_all_properties(symbol: str) -> dict:
    """Return all properties for an element as a dict."""
    if symbol not in ELEMENT_DATA:
        return {}
    return dict(zip(PROPERTY_NAMES, ELEMENT_DATA[symbol]))
